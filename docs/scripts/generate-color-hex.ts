// Turns the shipped theme's OKLCH colour tokens into hex codes for the /colors page, so people can copy
// a value and search engines can read them. Run after upgrading @radui/ui:
//   npx tsx scripts/generate-color-hex.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { toHex } from '../utils/theme-generator/scale'

// OKLCH to sRGB, clipping each channel the way browsers paint out-of-gamut colours today, so a copied
// hex matches the swatch on screen (the theme generator's chroma-reducing version would not).
function oklchToHex({ l, c, h }: { l: number; c: number; h: number }): string {
    const rad = (h * Math.PI) / 180
    const a = c * Math.cos(rad)
    const b = c * Math.sin(rad)
    const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3
    const lin = [
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
    ]
    const enc = (v: number) => {
        const x = Math.min(1, Math.max(0, v))
        return x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055
    }
    return toHex({ r: enc(lin[0]), g: enc(lin[1]), b: enc(lin[2]) })
}

const css = readFileSync('node_modules/@radui/ui/dist/themes/default.css', 'utf8')
// The minifier shortens some values to colour keywords (hsl(0 0% 50%) becomes grey).
const NAMED: Record<string, string> = { grey: '#808080', gray: '#808080', white: '#ffffff', black: '#000000' }
const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950', '1000']

function tokens(selector: string): Record<string, Record<string, string>> {
    const out: Record<string, Record<string, string>> = {}
    const blocks = css.split('}').filter((block) => block.split('{')[0].trim() === selector)
    for (const block of blocks) {
        for (const [, family, step, raw] of block.matchAll(/--rad-ui-color-([a-z]+)-(\d+):\s*([^;]+)/g)) {
            if (!STEPS.includes(step)) continue
            const value = raw.trim()
            const oklch = value.match(/^oklch\(([\d.]+)(%?)\s+([\d.]+)\s+([\d.]+)\)$/)
            let hex: string | null = null
            if (oklch) {
                const l = oklch[2] ? Number(oklch[1]) / 100 : Number(oklch[1])
                hex = oklchToHex({ l, c: Number(oklch[3]), h: Number(oklch[4]) })
            } else if (/^#[0-9a-f]{6}$/i.test(value)) hex = value.toLowerCase()
            else if (NAMED[value]) hex = NAMED[value]
            if (!hex) throw new Error(`Can't read --rad-ui-color-${family}-${step}: ${value}`)
            ;(out[family] ??= {})[step] = hex
        }
    }
    return out
}

const light = tokens(':root')
const dark = tokens('[data-rad-ui-theme=dark]')
const families = Object.keys(light).filter((f) => STEPS.every((s) => light[f][s] && dark[f]?.[s]))
if (families.length < 20) throw new Error(`Only found ${families.length} complete colour families; the theme file format changed`)

const data = Object.fromEntries(
    families.map((f) => [f, { light: STEPS.map((s) => light[f][s]), dark: STEPS.map((s) => dark[f][s]) }])
)
const version = JSON.parse(readFileSync('node_modules/@radui/ui/package.json', 'utf8')).version
writeFileSync(
    'utils/colors/palette-hex.ts',
    `// Generated by scripts/generate-color-hex.ts from @radui/ui ${version}. Do not edit by hand.\n` +
        `export const PALETTE_STEPS = ${JSON.stringify(STEPS)} as const\n\n` +
        `export const paletteHex: Record<string, { light: string[]; dark: string[] }> = ${JSON.stringify(data).replace(/\],"/g, "],\n        \"").replace(/},"/g, "},\n    \"")}\n`
)
console.log(`${families.length} families written from @radui/ui ${version}`)
